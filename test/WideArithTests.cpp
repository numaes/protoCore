// WideArithTests.cpp - the 64-bit digit primitives and the bignum division
// that is built on them.
//
// core/WideArith.h replaced MSVC's internal std::_Unsigned128 class.  Each
// primitive has up to three implementations (unsigned __int128, the MSVC x64
// intrinsics, and a portable 32-bit half-digit fallback); the fast one is
// checked on whichever platform runs this file, and the portable one on every
// platform, against the same table.
//
// THE EXPECTED VALUES WERE NOT PRODUCED BY PROTOCORE.  They were computed
// offline with Python's arbitrary-precision integers and are embedded here as
// literals, so a wrong result cannot agree with itself.
//
// The Integer division vectors exercise the rare steps of Knuth's Algorithm D
// (TAOCP vol. 2, 4.3.1) on 64-bit digits, which random operands essentially
// never reach (the add-back step D6 fires with probability about 2/2^64):
//
//   qhat_overflow  the top digit of the running remainder equals the divisor's
//                  top digit, so the trial quotient is 2^64 and must be
//                  corrected before it fits a digit
//   rhat_overflow  the trial remainder passes 2^64 during correction, which
//                  ends the correction loop early
//   D6             the trial quotient is still one too large after the
//                  correction, the multiply-and-subtract goes negative, and the
//                  divisor is added back
//
// They were found by an exhaustive search over operands built from the digits
// {0, 1, 2, 3, 2^32 - 1, 2^32, 2^63 - 1, 2^63, 2^63 + 1, 2^64 - 3, 2^64 - 2,
// 2^64 - 1}, running a Python model of protoCore's Algorithm D that records
// which of those steps each division takes; the tag on each row says which.
// Every row also runs with the four sign combinations: division truncates
// toward zero and the remainder takes the dividend's sign (Integer::divide and
// Integer::modulo).

