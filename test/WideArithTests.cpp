TEST(WideArith, Mul64x64MatchesPython) {
    for (const MulCase& c : kMul) {
        uint64_t hi = 0;
        EXPECT_EQ(wide::mul64x64(c.a, c.b, &hi), c.lo) << std::hex << c.a << " * " << c.b;
        EXPECT_EQ(hi, c.hi) << std::hex << c.a << " * " << c.b;
        uint64_t phi = 0;
        EXPECT_EQ(wide::mul64x64Portable(c.a, c.b, &phi), c.lo) << std::hex << c.a << " * " << c.b;
        EXPECT_EQ(phi, c.hi) << std::hex << c.a << " * " << c.b;
    }
}

TEST(WideArith, Div128by64MatchesPython) {
    for (const DivCase& c : kDiv) {
        uint64_t r = ~uint64_t{0};
        EXPECT_EQ(wide::div128by64(c.hi, c.lo, c.d, &r), c.q) << std::hex << c.hi << ":" << c.lo << " / " << c.d;
        EXPECT_EQ(r, c.r) << std::hex << c.hi << ":" << c.lo << " / " << c.d;
        uint64_t pr = ~uint64_t{0};
        EXPECT_EQ(wide::div128by64Portable(c.hi, c.lo, c.d, &pr), c.q) << std::hex << c.hi << ":" << c.lo << " / " << c.d;
        EXPECT_EQ(pr, c.r) << std::hex << c.hi << ":" << c.lo << " / " << c.d;
    }
}

TEST(WideArith, AddCarryAndSubBorrow) {
    const uint64_t M = ~uint64_t{0};
    uint64_t c = 9;
    EXPECT_EQ(wide::addCarry(M, 1, 0, &c), 0u);  EXPECT_EQ(c, 1u);
    EXPECT_EQ(wide::addCarry(M, 0, 1, &c), 0u);  EXPECT_EQ(c, 1u);
    EXPECT_EQ(wide::addCarry(M, M, 1, &c), M);   EXPECT_EQ(c, 1u);
    EXPECT_EQ(wide::addCarry(1, 2, 1, &c), 4u);  EXPECT_EQ(c, 0u);
    EXPECT_EQ(wide::addCarry(M - 1, 0, 1, &c), M); EXPECT_EQ(c, 0u);
    uint64_t b = 9;
    EXPECT_EQ(wide::subBorrow(0, 1, 0, &b), M);  EXPECT_EQ(b, 1u);
    EXPECT_EQ(wide::subBorrow(0, 0, 1, &b), M);  EXPECT_EQ(b, 1u);
    EXPECT_EQ(wide::subBorrow(0, M, 1, &b), 0u); EXPECT_EQ(b, 1u);
    EXPECT_EQ(wide::subBorrow(5, 2, 1, &b), 2u); EXPECT_EQ(b, 0u);
    EXPECT_EQ(wide::subBorrow(1, 0, 1, &b), 0u); EXPECT_EQ(b, 0u);
}

