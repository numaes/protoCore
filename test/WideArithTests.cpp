TEST(WideArith, KnuthDivisionRareStepsMatchPython) {
    ProtoSpace space;
    ProtoContext* ctx = space.rootContext;
    for (const KnuthCase& c : kKnuth) {
        const ProtoObject* u = Integer::fromString(ctx, c.u, 10);
        const ProtoObject* v = Integer::fromString(ctx, c.v, 10);
        EXPECT_EQ(decimal(ctx, Integer::divide(ctx, u, v)), c.q) << c.u << " / " << c.v << " [" << c.steps << "]";
        EXPECT_EQ(decimal(ctx, Integer::modulo(ctx, u, v)), c.r) << c.u << " % " << c.v << " [" << c.steps << "]";
        // q * v + r == u closes the loop through multiply and add as well.
        const ProtoObject* back = Integer::add(ctx, Integer::multiply(ctx, Integer::divide(ctx, u, v), v),
                                               Integer::modulo(ctx, u, v));
        EXPECT_EQ(decimal(ctx, back), c.u) << "q*v+r for " << c.u << " / " << c.v;
    }
}

// The SmallInteger fast paths no longer go through a 128-bit type: check the
// edges of the 54-bit SmallInteger range, where they hand over to the bignum.
TEST(WideArith, SmallIntegerFastPathEdges) {
    ProtoSpace space;
    ProtoContext* ctx = space.rootContext;
    const long long maxSmall = (1LL << 53) - 1;
    const long long minSmall = -(1LL << 53);
    auto L = [&](long long x) { return ctx->fromLong(x); };
    EXPECT_EQ(decimal(ctx, Integer::add(ctx, L(maxSmall), L(1))), "9007199254740992");
    EXPECT_EQ(decimal(ctx, Integer::subtract(ctx, L(minSmall), L(1))), "-9007199254740993");
    EXPECT_EQ(decimal(ctx, Integer::multiply(ctx, L(maxSmall), L(maxSmall))), "81129638414606663681390495662081");
    EXPECT_EQ(decimal(ctx, Integer::multiply(ctx, L(minSmall), L(minSmall))), "81129638414606681695789005144064");
    EXPECT_EQ(decimal(ctx, Integer::multiply(ctx, L(minSmall), L(maxSmall))), "-81129638414606672688589750403072");
    EXPECT_EQ(decimal(ctx, Integer::multiply(ctx, L(1LL << 26), L(1LL << 27))), "9007199254740992");
    EXPECT_EQ(decimal(ctx, Integer::multiply(ctx, L(-(1LL << 26)), L(1LL << 27))), "-9007199254740992");
    EXPECT_EQ(Integer::multiply(ctx, L(-(1LL << 26)), L(1LL << 27))->asLong(ctx), minSmall);
    EXPECT_EQ(decimal(ctx, Integer::shiftLeft(ctx, L(maxSmall), 10)), "9223372036854774784");
    EXPECT_EQ(decimal(ctx, Integer::shiftLeft(ctx, L(maxSmall), 11)), "18446744073709549568");
    EXPECT_EQ(decimal(ctx, Integer::shiftLeft(ctx, L(minSmall), 10)), "-9223372036854775808");
    EXPECT_EQ(decimal(ctx, Integer::shiftLeft(ctx, L(minSmall), 63)), "-83076749736557242056487941267521536");
    EXPECT_EQ(decimal(ctx, Integer::shiftLeft(ctx, L(-1), 63)), "-9223372036854775808");
    EXPECT_EQ(decimal(ctx, Integer::shiftLeft(ctx, L(1), 63)), "9223372036854775808");
    EXPECT_EQ(decimal(ctx, Integer::shiftLeft(ctx, L(3), 64)), "55340232221128654848");
}
